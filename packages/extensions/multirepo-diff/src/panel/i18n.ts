const ALIASES: ReadonlyArray<readonly [string, Locale]> = [
  ['pt', 'pt-BR'],
  ['zh-cn', 'zh-CN'],
  ['zh-tw', 'zh-TW'],
  ['zh', 'zh-CN'],
  ['en', 'en'],
  ['de', 'de'],
  ['fr', 'fr'],
  ['uk', 'uk'],
  ['es', 'es'],
  ['ko', 'ko'],
  ['pl', 'pl'],
  ['ja', 'ja'],
  ['tr', 'tr'],
];

export const normalizeLocale = (raw: string | null | undefined): Locale => {
  const lower = (raw ?? '').trim().toLowerCase();
  if (lower === '') return 'en';
  for (const [prefix, locale] of ALIASES) {
    if (lower === prefix || lower.startsWith(`${prefix}-`)) return locale;
  }
  return 'en';
};

export type Translator = (key: MessageKey, vars?: Record<string, string | number>) => string;

const interpolate = (template: string, vars?: Record<string, string | number>): string => {
  if (!vars) return template;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = vars[name];
    return value === undefined ? match : String(value);
  });
};

export const createTranslator = (locale: string | null | undefined): Translator => {
  const resolved = normalizeLocale(locale);
  const dict = DICTIONARIES[resolved];
  return (key, vars) => interpolate(dict[key] ?? en[key], vars);
};
